export class BuildingBlocksAssemblyWasmBounds {
  public clampToStructure(value: number, minBound: number, maxBound: number): number {
    return Math.max(minBound, Math.min(maxBound, value));
  }

  /** Valid Wasm 1.0 MVP binary exporting rect_perimeter(f64 w, f64 h) -> f64 = 2*(w+h) */
  public emitPerimeterWasm(): Uint8Array {
    // 2.0 in IEEE-754 f64 LE = 00 00 00 00 00 00 00 40
    return new Uint8Array([
      0x00, 0x61, 0x73, 0x6d, 0x01, 0x00, 0x00, 0x00,
      0x01, 0x07, 0x01, 0x60, 0x02, 0x7c, 0x7c, 0x01, 0x7c,
      0x03, 0x02, 0x01, 0x00,
      0x07, 0x12, 0x01, 0x0e, 0x72, 0x65, 0x63, 0x74, 0x5f, 0x70, 0x65, 0x72, 0x69, 0x6d, 0x65, 0x74, 0x65, 0x72, 0x00, 0x00,
      0x0a, 0x12, 0x01, 0x10, 0x00,
      0x20, 0x00, 0x20, 0x01, 0xa0, // w + h
      0x44, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x40, // 2.0
      0xa2, 0x0b, // mul; end
    ]);
  }
}

export const BuildingBlocksAssemblyWasmInstance = new BuildingBlocksAssemblyWasmBounds();
