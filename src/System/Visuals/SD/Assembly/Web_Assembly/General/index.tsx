/**
 * System/Visuals/SD/Assembly/Web_Assembly/General/index.tsx
 * Nearest-palette quantization and valid WebAssembly integer stride offset binary.
 */

export class VisualsSDAssemblyWasmQuantizer {
  public quantizeUniformLevels(channel8: number, levels: number = 32): number {
    const step = 255 / Math.max(1, levels - 1);
    return Math.round(Math.round(Math.max(0, Math.min(255, channel8)) / step) * step);
  }

  /** Valid Wasm 1.0 MVP binary exporting pixel_stride_offset(i32 y, i32 width) -> i32 */
  public emitStrideOffsetWasm(): Uint8Array {
    return new Uint8Array([
      0x00, 0x61, 0x73, 0x6d, 0x01, 0x00, 0x00, 0x00,
      0x01, 0x07, 0x01, 0x60, 0x02, 0x7f, 0x7f, 0x01, 0x7f,
      0x03, 0x02, 0x01, 0x00,
      0x07, 0x17, 0x01, 0x13, 0x70, 0x69, 0x78, 0x65, 0x6c, 0x5f, 0x73, 0x74, 0x72, 0x69, 0x64, 0x65, 0x5f, 0x6f, 0x66, 0x66, 0x73, 0x65, 0x74, 0x00, 0x00,
      0x0a, 0x09, 0x01, 0x07, 0x00, 0x20, 0x00, 0x20, 0x01, 0x6c, 0x0b,
    ]);
  }
}

export const VisualsSDAssemblyWasmInstance = new VisualsSDAssemblyWasmQuantizer();
